// Builds src/components/categoryIconPaths.ts, one path per CATEGORY_ICONS key,
// from Phosphor's regular weight. Phosphor's per-icon modules carry all six
// weights (~650 KB for the catalog); this carries one (~70 KB compressed). It
// ships in the JS bundle rather than as an external sprite: <use> into a
// separate file drew the icon picker's grid seconds late, even from cache.
// Run after adding an icon to CATEGORY_ICONS: npm run gen:category-icons
import { readFileSync, writeFileSync } from 'node:fs'

const catalog = readFileSync('src/lib/categoryIcons.ts', 'utf8')
const block = catalog.slice(catalog.indexOf('export const CATEGORY_ICONS = {'), catalog.indexOf('\n}\n', catalog.indexOf('export const CATEGORY_ICONS = {')))
const keys = [...block.matchAll(/^ {2}(\w+):/gm)].map((m) => m[1])

const paths = Object.fromEntries(keys.map((key) => {
  const defs = readFileSync(`node_modules/@phosphor-icons/react/dist/defs/${key}.es.js`, 'utf8')
  const regular = defs.slice(defs.indexOf('"regular"'))
  const d = regular.match(/d: "([^"]+)"/)?.[1]
  if (!d) throw new Error(`No regular path for ${key}`)
  return [key, d]
}))

const body = Object.entries(paths).map(([k, d]) => `  ${k}: '${d}',`).join('\n')
writeFileSync('src/components/categoryIconPaths.ts',
  `// Generated by scripts/gen-category-icons.mjs. Don't edit.\nexport const CATEGORY_ICON_PATHS: Record<string, string> = {\n${body}\n}\n`)
console.log(`${keys.length} icons`)
