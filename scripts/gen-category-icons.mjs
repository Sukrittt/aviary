// Builds public/category-icons.svg, one <symbol> per CATEGORY_ICONS key, from
// Phosphor's regular weight. Phosphor's per-icon modules carry all six weights
// (~650 KB for the catalog); the sprite carries one (~80 KB, ~29 KB gzipped),
// costs no JS, and the browser caches it across pages.
// Run after adding an icon to CATEGORY_ICONS: npm run gen:category-icons
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'

const catalog = readFileSync('src/lib/categoryIcons.ts', 'utf8')
const block = catalog.slice(catalog.indexOf('export const CATEGORY_ICONS = {'), catalog.indexOf('\n}\n', catalog.indexOf('export const CATEGORY_ICONS = {')))
const keys = [...block.matchAll(/^ {2}(\w+):/gm)].map((m) => m[1])

const symbols = keys.map((key) => {
  const defs = readFileSync(`node_modules/@phosphor-icons/react/dist/defs/${key}.es.js`, 'utf8')
  const regular = defs.slice(defs.indexOf('"regular"'))
  const d = regular.match(/d: "([^"]+)"/)?.[1]
  if (!d) throw new Error(`No regular path for ${key}`)
  return `<symbol id="${key}" viewBox="0 0 256 256"><path d="${d}"/></symbol>`
})

const svg = `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join('')}</svg>\n`
writeFileSync('public/category-icons.svg', svg)
// A content hash in the URL so the long cache in next.config.ts is safe.
const hash = createHash('sha256').update(svg).digest('hex').slice(0, 10)
writeFileSync('src/components/categoryIconSprite.ts',
  `// Generated by scripts/gen-category-icons.mjs. Don't edit.\nexport const CATEGORY_ICON_SPRITE = '/category-icons.svg?v=${hash}'\n`)
console.log(`${keys.length} icons, ${svg.length} bytes`)
